#define NGLYPH ((int)(sizeof FONT / sizeof FONT[0]))

static const uint8_t *glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    for (int i = 0; i < NGLYPH; i++) if (FONT[i].c == c) return FONT[i].col;
    for (int i = 0; i < NGLYPH; i++) if (FONT[i].c == '?') return FONT[i].col;
    return FONT[0].col;
}

int dw2_text_w(int scale, const char *s) { return (int)strlen(s) * 6 * scale; }

void dw2_text_a(SDL_Renderer *r, int x, int y, int scale, uint8_t cr, uint8_t cg, uint8_t cb, int alpha, const char *s) {
    SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_BLEND);
    SDL_SetRenderDrawColor(r, cr, cg, cb, (Uint8)alpha);
    for (const char *p = s; *p; p++, x += 6 * scale) {
        const uint8_t *g = glyph(*p);
        for (int cx = 0; cx < 5; cx++) for (int cy = 0; cy < 7; cy++)
            if (g[cx] & (1 << cy)) { SDL_Rect d = { x + cx * scale, y + cy * scale, scale, scale }; SDL_RenderFillRect(r, &d); }
    }
}

void dw2_text(SDL_Renderer *r, int x, int y, int scale, uint8_t cr, uint8_t cg, uint8_t cb, const char *s) {
    dw2_text_a(r, x, y, scale, cr, cg, cb, 255, s);
}

void dw2_text_c(SDL_Renderer *r, int cx, int y, int scale, uint8_t cr, uint8_t cg, uint8_t cb, const char *s) {
    dw2_text(r, cx - dw2_text_w(scale, s) / 2, y, scale, cr, cg, cb, s);
}
